#!/usr/bin/env python3
"""Generate independent AUR recipes from Git or a verified release manifest."""
import argparse
import json
from pathlib import Path
import shutil
import subprocess

import release

ROOT = Path(__file__).resolve().parents[1]


def package_body(product, source):
    lines = [f'  cd "{source}"',
             f'  install -Dm755 {"target/$_target/release/" if source == "$srcdir/hireferry" else ""}{"hireferry" if product == "server" else "hfy"} "$pkgdir/usr/bin/{"hireferry" if product == "server" else "hfy"}"',
             '  install -Dm644 LICENSE "$pkgdir/usr/share/licenses/$pkgname/LICENSE"']
    if product == 'server':
        arch = 'packaging/arch' if source == '$srcdir/hireferry' else '$srcdir'
        lines += [f'  install -Dm644 "{arch}/hireferry.service" "$pkgdir/usr/lib/systemd/system/hireferry.service"',
                  f'  install -Dm644 "{arch}/hireferry.sysusers" "$pkgdir/usr/lib/sysusers.d/hireferry.conf"',
                  f'  install -Dm644 "{arch}/hireferry.tmpfiles" "$pkgdir/usr/lib/tmpfiles.d/hireferry.conf"',
                  '  install -Dm644 config.example.toml "$pkgdir/usr/share/hireferry/config.example.toml"',
                  '  install -Dm644 THIRD_PARTY_NOTICES "$pkgdir/usr/share/doc/hireferry-server/THIRD_PARTY_NOTICES"',
                  '  install -Dm644 docs/self-hosting.md docs/deployment-handoff.md docs/aur.md -t "$pkgdir/usr/share/doc/hireferry-server/"']
    else:
        lines += ['  install -Dm644 docs/cli.md "$pkgdir/usr/share/doc/hireferry-cli/README.md"',
                  '  install -d "$pkgdir/usr/share/hireferry-cli/skills"',
                  '  cp -r skills/hireferry "$pkgdir/usr/share/hireferry-cli/skills/"',
                  '  install -Dm755 scripts/install-skill.sh "$pkgdir/usr/share/hireferry-cli/scripts/install-skill.sh"']
    return '\n'.join(lines)


def render(product, variant, pkgver, manifest=None):
    base = f'hireferry-{product}'
    name = f'{base}-{variant}'
    description = 'Self-hosted recruitment server with an embedded web UI' if product == 'server' else 'Command-line client for HireFerry (hfy)'
    dependencies = "'glibc' 'gcc-libs' 'openssl' 'ca-certificates' 'systemd'" if product == 'server' else ("'ca-certificates'" if variant == 'bin' else "'glibc' 'gcc-libs' 'ca-certificates'")
    text = f'''# Maintainer: HireFerry contributors <support@lmm.best>
# Generated by scripts/aur.py; edit the generator in the upstream repository.
pkgname={name}
pkgver={pkgver}
pkgrel=1
pkgdesc='{description}'
arch=('x86_64' 'aarch64')
url='https://github.com/TokenNotIncluded/hireferry'
license=('AGPL-3.0-or-later')
depends=({dependencies})
provides=('{base}')
conflicts=('{base}')
'''
    if product == 'cli':
        text += "optdepends=('xdg-utils: open browser for interactive login')\n"
    if variant == 'git':
        cargo_package = 'hireferry' if product == 'server' else 'hireferry-cli'
        cargo_toml = 'Cargo.toml' if product == 'server' else 'crates/hireferry-cli/Cargo.toml'
        text += f'''makedepends=('cargo' 'git'{" 'pkgconf'" if product == 'server' else ''})
options=('!lto')
source=('hireferry::git+https://github.com/TokenNotIncluded/hireferry.git#branch=main')
sha256sums=('SKIP')
_target="$CARCH-unknown-linux-gnu"

pkgver() {{
  cd "$srcdir/hireferry"
  local version
  version=$(sed -n 's/^version = "\\([^"]*\\)"$/\\1/p' {cargo_toml} | head -n 1)
  printf '%s.r%s.g%s' "${{version//-/.}}" "$(git rev-list --count HEAD)" "$(git rev-parse --short HEAD)"
}}

prepare() {{
  cd "$srcdir/hireferry"
  cargo fetch --locked --target "$_target"
}}

build() {{
  cd "$srcdir/hireferry"
  CARGO_TARGET_DIR=target cargo build --frozen --release --target "$_target" -p {cargo_package}
}}

check() {{
  cd "$srcdir/hireferry"
  CARGO_TARGET_DIR=target cargo test --frozen --target "$_target" -p {cargo_package}
}}

package() {{
{package_body(product, '$srcdir/hireferry')}
}}
'''
    else:
        assets = {a['architecture']:a for a in manifest['assets'] if a['product'] == product and a['platform'] == 'Linux'}
        if set(assets) != {'x86_64', 'aarch64'}:
            raise ValueError('Binary AUR packages require exactly x86_64 and aarch64 Linux assets')
        for arch, asset in assets.items():
            expected = f'{arch}-unknown-linux-' + ('gnu' if product == 'server' else 'musl')
            if asset['target'] != expected or asset['format'] != 'tar.gz':
                raise ValueError('Unexpected AUR binary target or archive format')
            text += f"source_{arch}=('{asset['url']}')\nsha256sums_{arch}=('{asset['sha256']}')\n"
        text += "options=('!strip' '!debug')\n"
        if product == 'server':
            text += "source=('hireferry.service' 'hireferry.sysusers' 'hireferry.tmpfiles')\n"
            text += 'sha256sums=(' + ' '.join("'"+release.digest(ROOT/'packaging/arch'/f)+"'" for f in ('hireferry.service','hireferry.sysusers','hireferry.tmpfiles')) + ')\n'
        target = '$CARCH-unknown-linux-' + ('gnu' if product == 'server' else 'musl')
        text += f'''\npackage() {{
{package_body(product, f'$srcdir/hireferry-{product}-{manifest["versions"][product]}-{target}')}
}}
'''
    return name, text


def generate(args):
    manifest = release.validate_manifest(json.loads(args.manifest.read_text())) if args.manifest else None
    if args.variant == 'bin':
        if manifest is None or args.product not in manifest['versions']:
            raise ValueError('A binary recipe requires a verified manifest for the product')
        if manifest['repository'] != 'TokenNotIncluded/hireferry':
            raise ValueError('AUR recipes require the official upstream repository')
        pkgver = manifest['versions'][args.product]
        release.stable_version(pkgver)
    else:
        pkgver = release.package_version(args.product).replace('-', '.')
        pkgver += '.r' + subprocess.check_output(['git','rev-list','--count','HEAD'],cwd=ROOT,text=True).strip()
        pkgver += '.g' + subprocess.check_output(['git','rev-parse','--short','HEAD'],cwd=ROOT,text=True).strip()
    name, text = render(args.product, args.variant, pkgver, manifest)
    folder = args.out / name
    folder.mkdir(parents=True, exist_ok=True)
    (folder/'PKGBUILD').write_text(text)
    if args.product == 'server' and args.variant == 'bin':
        for file in ('hireferry.service','hireferry.sysusers','hireferry.tmpfiles'):
            shutil.copyfile(ROOT/'packaging/arch'/file, folder/file)
    info = subprocess.check_output(['makepkg','--printsrcinfo'], cwd=folder, text=True)
    (folder/'.SRCINFO').write_text(info)
    print(folder)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--product', choices=('server','cli'), required=True)
    parser.add_argument('--variant', choices=('git','bin'), required=True)
    parser.add_argument('--manifest', type=Path)
    parser.add_argument('--out', type=Path, default=ROOT/'packaging/aur')
    try:
        generate(parser.parse_args())
    except (ValueError, KeyError, OSError, subprocess.CalledProcessError) as error:
        parser.exit(1, f'aur: {error}\n')
