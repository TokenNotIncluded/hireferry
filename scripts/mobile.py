#!/usr/bin/env python3
"""Build real Tauri mobile artifacts; no credentials are written into the repository.

PR builds use Android debug signing / unsigned iOS simulator apps. Release builds
require maintainer-owned credentials and remain separate from desktop downloads.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import plistlib
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
import time
import xml.etree.ElementTree as ET
import zipfile

ROOT = Path(__file__).resolve().parents[1]
DESKTOP = ROOT / "desktop"
TAURI = DESKTOP / "src-tauri"
ANDROID_SDK = "37"
ANDROID_BUILD_TOOLS = "37.0.0"
ANDROID_NDK = "29.0.13846066"
ANDROID_TARGETS = {
    "aarch64": "aarch64-linux-android",
    "x86_64": "x86_64-linux-android",
    "armv7": "armv7-linux-androideabi",
    "i686": "i686-linux-android",
}
IOS_TARGETS = {
    "aarch64": "aarch64-apple-ios",
    "aarch64-sim": "aarch64-apple-ios-sim",
    "x86_64": "x86_64-apple-ios",
}
ANDROID_SIGNING = (
    "HF_ANDROID_KEYSTORE_PATH", "HF_ANDROID_KEYSTORE_PASSWORD",
    "HF_ANDROID_KEY_ALIAS", "HF_ANDROID_KEY_PASSWORD", "HF_ANDROID_CERT_SHA256",
)
SIGNING_MARKER = "// HireFerry release signing (environment only; generated by scripts/mobile.py)."
SIGNING_GRADLE = '''
// HireFerry release signing (environment only; generated by scripts/mobile.py).
val hfSigningKeys = listOf("HF_ANDROID_KEYSTORE_PATH", "HF_ANDROID_KEYSTORE_PASSWORD", "HF_ANDROID_KEY_ALIAS", "HF_ANDROID_KEY_PASSWORD")
if (hfSigningKeys.all { !System.getenv(it).isNullOrBlank() }) {
    android {
        signingConfigs {
            create("hireferryRelease") {
                storeFile = file(System.getenv("HF_ANDROID_KEYSTORE_PATH"))
                storePassword = System.getenv("HF_ANDROID_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("HF_ANDROID_KEY_ALIAS")
                keyPassword = System.getenv("HF_ANDROID_KEY_PASSWORD")
            }
        }
        buildTypes.getByName("release").signingConfig = signingConfigs.getByName("hireferryRelease")
    }
}
'''


class MobileError(RuntimeError):
    pass


def run(args, *, cwd=DESKTOP, capture=False, env=None):
    # Never echo environment values: signing passwords are intentionally not argv.
    print("+ " + " ".join(str(v) for v in args), flush=True)
    result = subprocess.run([str(v) for v in args], cwd=cwd, env=env,
                            text=True, capture_output=capture)
    if result.returncode:
        if capture:
            print(result.stdout, end="", file=sys.stderr)
            print(result.stderr, end="", file=sys.stderr)
        raise MobileError(f"{args[0]} exited with status {result.returncode}")
    return result.stdout if capture else ""


def cli(*args):
    # Use the checked-in lockfile's CLI; do not let npx silently fetch a version.
    # The npm lifecycle environment also lets Tauri generate a working command
    # for Xcode/Gradle to re-enter the CLI from their nested project directory.
    # Invoking .bin/tauri directly generates `node tauri ...`, which cannot find
    # its script when Xcode executes the Build Rust Code phase in gen/apple.
    binary = DESKTOP / "node_modules" / ".bin" / ("tauri.cmd" if os.name == "nt" else "tauri")
    if not binary.exists():
        raise MobileError("Install the pinned CLI first: cd desktop && npm ci")
    return ["npm.cmd" if os.name == "nt" else "npm", "run", "tauri", "--", *args]


def sdk_root():
    value = os.environ.get("ANDROID_HOME") or os.environ.get("ANDROID_SDK_ROOT")
    if not value or not Path(value).is_dir():
        raise MobileError("Set ANDROID_HOME to an installed Android SDK")
    return Path(value)


def android_tool(name):
    suffix = ".bat" if os.name == "nt" and name == "apksigner" else (".exe" if os.name == "nt" else "")
    folder = "platform-tools" if name == "adb" else f"build-tools/{ANDROID_BUILD_TOOLS}"
    path = sdk_root() / folder / f"{name}{suffix}"
    if not path.is_file():
        raise MobileError(f"Missing Android tool: {path}")
    return path


def doctor(target_platform):
    missing = []
    for command in ("node", "npm", "cargo", "rustup", "java") if target_platform == "android" else ("node", "npm", "cargo", "rustup", "xcodebuild", "xcrun", "pod"):
        if not shutil.which(command):
            missing.append(command)
    if target_platform == "ios" and platform.system() != "Darwin":
        missing.append("macOS + full Xcode (iOS builds cannot run on Linux/Windows)")
    if target_platform == "android":
        try:
            root = sdk_root()
            ndk = Path(os.environ.get("NDK_HOME", root / "ndk" / ANDROID_NDK))
            for item in (root / "platforms" / f"android-{ANDROID_SDK}",
                         root / "build-tools" / ANDROID_BUILD_TOOLS, ndk / "source.properties"):
                if not item.exists():
                    missing.append(str(item))
        except MobileError as error:
            missing.append(str(error))
    if missing:
        raise MobileError("Missing prerequisites:\n  - " + "\n  - ".join(missing))
    print(f"{target_platform}: host tools found; compile and device checks run during build/smoke")


def prepare_android_signing(project):
    path = project / "app" / "build.gradle.kts"
    content = path.read_text()
    if SIGNING_MARKER not in content:
        path.write_text(content + SIGNING_GRADLE)


def require_android_signing():
    missing = [key for key in ANDROID_SIGNING if not os.environ.get(key)]
    if missing:
        raise MobileError("Android release requires maintainer signing: " + ", ".join(missing))
    if not Path(os.environ["HF_ANDROID_KEYSTORE_PATH"]).is_file():
        raise MobileError("HF_ANDROID_KEYSTORE_PATH must identify a real keystore")
    fingerprint = os.environ["HF_ANDROID_CERT_SHA256"].replace(":", "").lower()
    if not re.fullmatch(r"[0-9a-f]{64}", fingerprint):
        raise MobileError("HF_ANDROID_CERT_SHA256 must be the expected certificate SHA-256")
    return fingerprint


def initialize(target_platform):
    doctor(target_platform)
    project = TAURI / "gen" / ("android" if target_platform == "android" else "apple")
    marker = project / ("settings.gradle" if target_platform == "android" else "project.yml")
    # Tauri currently emits settings.gradle, but accept a Kotlin DSL template too.
    initialized = marker.exists() or (target_platform == "android" and (project / "settings.gradle.kts").exists())
    if not initialized:
        run(cli(target_platform, "init", "--ci", "--skip-targets-install"))
    if target_platform == "android":
        prepare_android_signing(project)
    # Generate platform icons from the checked-in vector without rewriting the
    # desktop icon set. The platform project itself is reproducible/ignored.
    icons = TAURI / "gen" / "mobile-icons"
    run(cli("icon", str(TAURI / "icons" / "icon.svg"), "--output", str(icons)))
    if target_platform == "android":
        shutil.copytree(icons / "android", project / "app" / "src" / "main" / "res", dirs_exist_ok=True)
    else:
        shutil.copytree(icons / "ios", project / "Assets.xcassets" / "AppIcon.appiconset", dirs_exist_ok=True)
    return project


def sha256(path):
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def verify_android(path, expected_cert=None):
    if path.suffix == ".apk":
        output = run([android_tool("apksigner"), "verify", "--verbose", "--print-certs", path], capture=True)
        found = re.search(r"certificate SHA-256 digest:\s*([0-9a-fA-F:]+)", output)
        if not found:
            raise MobileError("APK signature verifier returned no certificate digest")
        fingerprint = found.group(1).replace(":", "").lower()
        details = run([android_tool("aapt"), "dump", "badging", path], capture=True)
        package = re.search(r"package: name='([^']+)' versionCode='([^']+)' versionName='([^']+)'", details)
        if not package:
            raise MobileError("Unable to read APK package/version metadata")
        metadata = {"package_id": package.group(1), "version_code": int(package.group(2)), "version": package.group(3)}
    elif path.suffix == ".aab":
        verify_env = dict(os.environ, LC_ALL="C", LANG="C")
        output = run(["jarsigner", "-verify", path], capture=True, env=verify_env)
        if "jar verified" not in output.lower():
            raise MobileError("AAB is unsigned or its JAR signature did not verify")
        certificate = run(["keytool", "-printcert", "-jarfile", path], capture=True, env=verify_env)
        found = re.search(r"SHA256:\s*([0-9a-fA-F:]+)", certificate)
        if not found:
            raise MobileError("AAB signature has no readable SHA-256 certificate digest")
        fingerprint = found.group(1).replace(":", "").lower()
        metadata = {}
    else:
        raise MobileError("Android artifact must be .apk or .aab")
    if expected_cert and fingerprint != expected_cert:
        raise MobileError("Signing certificate differs from HF_ANDROID_CERT_SHA256")
    return {**metadata, "certificate_sha256": fingerprint, "signature_verified": True}


def verify_ios(path, expected_team):
    with tempfile.TemporaryDirectory(prefix="hireferry-ipa-") as directory:
        root = Path(directory)
        with zipfile.ZipFile(path) as archive:
            for name in archive.namelist():
                if Path(name).is_absolute() or ".." in Path(name).parts:
                    raise MobileError("IPA contains an unsafe archive path")
        # Preserve executable bits and framework symlinks for codesign.
        run(["ditto", "-x", "-k", path, root])
        applications = list((root / "Payload").glob("*.app"))
        if len(applications) != 1:
            raise MobileError("IPA must contain exactly one application")
        application = applications[0]
        run(["codesign", "--verify", "--deep", "--strict", application])
        # codesign emits public signing metadata on stderr, including on success.
        result = subprocess.run(["codesign", "-d", "--verbose=4", str(application)], capture_output=True, text=True, check=True)
        match = re.search(r"^TeamIdentifier=(.+)$", result.stderr, re.MULTILINE)
        if not match or match.group(1) != expected_team:
            raise MobileError("IPA signing team differs from APPLE_DEVELOPMENT_TEAM")
        with (application / "Info.plist").open("rb") as source:
            info = plistlib.load(source)
        if info.get("CFBundleIdentifier") != "best.lmm.hireferry":
            raise MobileError("IPA application ID differs from best.lmm.hireferry")
        profile = application / "embedded.mobileprovision"
        if not profile.is_file():
            raise MobileError("Signed iOS application has no embedded provisioning profile")
        return {"signature_verified": True, "team_id": expected_team,
                "package_id": info["CFBundleIdentifier"],
                "version": info.get("CFBundleShortVersionString"),
                "build_number": info.get("CFBundleVersion")}


def write_manifest(output, records, args):
    manifest = {
        "schema_version": 1, "platform": args.platform, "variant": args.variant,
        "distribution": "engineering-test" if args.variant == "debug" or args.simulator else "maintainer-signed",
        "simulator_only": bool(args.platform == "ios" and args.simulator),
        "targets": args.target, "artifacts": records,
    }
    (output / "mobile-artifacts.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (output / "SHA256SUMS").write_text("".join(f"{row['sha256']}  {row['filename']}\n" for row in records))
    print(f"Verified {len(records)} artifact(s): {output}")


def build(args):
    if args.platform == "android":
        expected = require_android_signing() if args.variant == "release" else None
        targets = args.target or ["aarch64"]
        mapping = ANDROID_TARGETS
    else:
        if args.simulator:
            targets = args.target or ["aarch64-sim" if platform.machine() == "arm64" else "x86_64"]
            if any(t not in ("aarch64-sim", "x86_64") for t in targets):
                raise MobileError("--simulator only accepts aarch64-sim or x86_64")
        else:
            targets = args.target or ["aarch64"]
            if targets != ["aarch64"]:
                raise MobileError("iOS device builds use --target aarch64")
            if not re.fullmatch(r"[A-Z0-9]{10}", os.environ.get("APPLE_DEVELOPMENT_TEAM", "")):
                raise MobileError("iOS device signing requires a real APPLE_DEVELOPMENT_TEAM and configured signing credentials")
        mapping = IOS_TARGETS
        expected = None
    if len(set(targets)) != len(targets) or any(t not in mapping for t in targets):
        raise MobileError(f"Invalid or duplicate {args.platform} target")
    args.target = targets
    doctor(args.platform)
    run(["rustup", "target", "add", *[mapping[t] for t in targets]])
    project = initialize(args.platform)
    command = cli(args.platform, "build", "--ci")
    for target in targets:
        command += ["--target", target]
    if args.variant == "debug":
        command.append("--debug")
    if args.platform == "android":
        for kind in (["apk", "aab"] if args.format == "both" else [args.format]):
            command.append(f"--{kind}")
        # Only this profile's generated outputs are removed. A stale build must
        # never be relabeled as the current verified artifact.
        for folder in [project / "app" / "build" / "outputs" / "apk" / "universal" / args.variant,
                       project / "app" / "build" / "outputs" / "bundle" / ("universal" + args.variant.title())]:
            if folder.exists():
                shutil.rmtree(folder)
    elif args.simulator:
        command.append("--no-sign")
    else:
        command += ["--export-method", args.export_method]
        if args.build_number is not None:
            command += ["--build-number", str(args.build_number)]
    command += ["--", "--locked"]
    run(command)
    output = Path(args.output).resolve()
    output.mkdir(parents=True, exist_ok=True)
    records = []
    if args.platform == "android":
        formats = ["apk", "aab"] if args.format == "both" else [args.format]
        for kind in formats:
            files = list((project / "app" / "build" / "outputs" / ("apk" if kind == "apk" else "bundle")).rglob(f"*.{kind}"))
            files = [p for p in files if args.variant.lower() in p.as_posix().lower()]
            if len(files) != 1:
                raise MobileError(f"Expected exactly one fresh universal {kind}; found {len(files)}")
            metadata = verify_android(files[0], expected)
            if kind == "apk":
                expected_id = "best.lmm.hireferry" + (".debug" if args.variant == "debug" else "")
                if metadata["package_id"] != expected_id:
                    raise MobileError("APK application ID does not match the requested build variant")
            destination = output / f"hireferry-android-{'-'.join(targets)}-{args.variant}.{kind}"
            shutil.copy2(files[0], destination)
            records.append({"filename": destination.name, "bytes": destination.stat().st_size, "sha256": sha256(destination), **metadata})
    else:
        for target in targets:
            arch = "arm64" if target.startswith("aarch64") else "x86_64"
            directory = project / "build" / arch
            candidates = list(directory.glob("*.app" if args.simulator else "*.ipa"))
            if len(candidates) != 1:
                raise MobileError(f"Expected one iOS {'simulator app' if args.simulator else 'IPA'} at {directory}")
            if args.simulator:
                destination = output / f"hireferry-ios-{target}-simulator.app.tar.gz"
                with tarfile.open(destination, "w:gz") as archive:
                    archive.add(candidates[0], arcname=candidates[0].name)
            else:
                destination = output / f"hireferry-ios-{target}-{args.export_method}.ipa"
                shutil.copy2(candidates[0], destination)
            metadata = {"signature_verified": False} if args.simulator else verify_ios(destination, os.environ["APPLE_DEVELOPMENT_TEAM"])
            records.append({"filename": destination.name, "bytes": destination.stat().st_size, "sha256": sha256(destination), **metadata})
    write_manifest(output, records, args)


def smoke_android(args):
    artifact = Path(args.artifact).resolve()
    metadata = verify_android(artifact)
    package = metadata["package_id"]
    adb = android_tool("adb")
    command = [adb] + (["-s", args.serial] if args.serial else [])
    run(command + ["wait-for-device"])
    run(command + ["install", "-r", artifact])
    run(command + ["logcat", "-c"])
    run(command + ["shell", "am", "force-stop", package])
    launch = run(command + ["shell", "am", "start", "-W", "-n", f"{package}/best.lmm.hireferry.MainActivity"], capture=True)
    if "Status: ok" not in launch:
        raise MobileError("Android activity did not report a successful launch")
    deadline = time.monotonic() + 45
    layout = ""
    while time.monotonic() < deadline:
        run(command + ["shell", "uiautomator", "dump", "/sdcard/hireferry-smoke.xml"], capture=True)
        layout = run(command + ["shell", "cat", "/sdcard/hireferry-smoke.xml"], capture=True)
        try:
            root = ET.fromstring(layout)
            text = " ".join(n.attrib.get("text", "") + " " + n.attrib.get("content-desc", "") for n in root.iter())
            if "hireferry.lmm.best" in text and ("workspace" in text.lower() or "工作台" in text):
                break
        except ET.ParseError:
            pass
        time.sleep(1)
    else:
        raise MobileError("Installed APK did not render the connection screen within 45 seconds")
    log = run(command + ["logcat", "-d", "-s", "AndroidRuntime:E"], capture=True)
    if "FATAL EXCEPTION" in log:
        raise MobileError("Android runtime reported a fatal exception")
    output = Path(args.output).resolve()
    output.mkdir(parents=True, exist_ok=True)
    (output / "android-launch.xml").write_text(layout)
    screenshot = subprocess.run([str(x) for x in command] + ["exec-out", "screencap", "-p"], check=True, capture_output=True)
    (output / "android-launch.png").write_bytes(screenshot.stdout)
    (output / "android-smoke.json").write_text(json.dumps({"package_id": package, "sha256": sha256(artifact), "installed": True, "launcher_rendered": True}, indent=2) + "\n")
    print("Android APK installed and rendered the local connection screen")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    for name in ("doctor", "init"):
        command = commands.add_parser(name)
        command.add_argument("platform", choices=("android", "ios"))
    command = commands.add_parser("build")
    command.add_argument("platform", choices=("android", "ios"))
    command.add_argument("--variant", choices=("debug", "release"), default="debug")
    command.add_argument("--target", action="append", default=[])
    command.add_argument("--format", choices=("apk", "aab", "both"), default="both")
    command.add_argument("--simulator", action="store_true")
    command.add_argument("--export-method", choices=("app-store-connect", "release-testing", "debugging"), default="app-store-connect")
    command.add_argument("--build-number", type=int)
    command.add_argument("--output", default=str(ROOT / "artifacts" / "mobile"))
    command = commands.add_parser("smoke-android")
    command.add_argument("artifact")
    command.add_argument("--serial")
    command.add_argument("--output", default=str(ROOT / "artifacts" / "mobile" / "smoke"))
    args = parser.parse_args()
    try:
        if args.command == "doctor":
            doctor(args.platform)
        elif args.command == "init":
            initialize(args.platform)
        elif args.command == "build":
            if args.platform == "android" and args.simulator:
                raise MobileError("Android emulators use --target x86_64, not --simulator")
            build(args)
        else:
            smoke_android(args)
    except (MobileError, OSError, subprocess.CalledProcessError) as error:
        print(f"mobile: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
